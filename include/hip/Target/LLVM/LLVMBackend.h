#ifndef LLVM_BACKEND_H
#define LLVM_BACKEND_H

#include <llvm/IR/LLVMContext.h>
#include <llvm/IR/Module.h>
#include <llvm/Target/TargetMachine.h>
#include <mlir/IR/BuiltinOps.h>

#include <memory>
#include <string>

namespace hipdnn {

// LLVMBackend — MLIR → optimized LLVM bitcode for the JIT-loaded per-model
// artifact.
//
// The native-DLL output path that used to live here was retired with the
// switch to in-process ORC JIT (see
// backend-mlir-compiler/custom-op-mlir/src/BitcodeJIT.h): hip-compiler.dll
// now emits binary LLVM bitcode that the EP DLL JIT-compiles in-process.
// Codegen happens on the runtime side, so this backend no longer needs
// TargetMachine, object-file emission, or LLD.
class LLVMBackend {
public:
  LLVMBackend() = default;
  ~LLVMBackend() = default;

  // MLIR → LLVM IR translation. Translates an MLIR module already lowered
  // to the LLVM dialect into in-memory LLVM IR. Returns nullptr on failure.
  std::unique_ptr<llvm::Module>
  translateMLIRtoLLVMIR(mlir::ModuleOp mlirModule,
                        llvm::LLVMContext &llvmContext);

  // LLVM IR optimization. Runs the standard PerModule pipeline at the
  // given level (0-3). Level 2 is the default for production compiles.
  void optimizeLLVMIR(llvm::Module *module, int optLevel);

  // Emit binary LLVM bitcode to `outputPath`. This is the canonical
  // production output: BitcodeJIT in the EP DLL re-parses these bytes
  // via llvm::parseBitcodeFile and hands them to ORC LLJIT. Returns
  // true on success.
  bool emitBitcode(llvm::Module *module, const std::string &outputPath);

  // Link the embedded runtime.bc into `destModule`. The runtime bitcode
  // ships inside hip-compiler.dll (generated by lib/Runtime/CMakeLists.txt)
  // and is merged in here so the host-side runtime functions
  // (`hipdnn_ep_*`, `wrap_*`) are internal symbols of the bitcode the EP
  // JITs -- they don't have to be exported from any DLL. Returns true on
  // success.
  bool linkRuntimeModule(llvm::Module *destModule);
};

} // namespace hipdnn

#endif // LLVM_BACKEND_H
